"""Regenerates notebooks/seed_chunks.py from the rag_app documents (same chunker as Topic 3)."""

import json
import logging
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RAG_APP = ROOT.parent / "rag_app"
sys.path.insert(0, str(RAG_APP))

from rag import build_chunks, clean_documents  # noqa: E402

logger = logging.getLogger(__name__)

OUTPUT = ROOT / "notebooks" / "seed_chunks.py"


def main() -> None:
    logging.basicConfig(level=logging.INFO)
    chunks = build_chunks(clean_documents(RAG_APP / "docs"), 30, 5)
    rows = [
        {"chunk_id": c.chunk_id, "source": c.source, "doc_type": c.doc_type, "text": c.text}
        for c in chunks
    ]
    OUTPUT.write_text(
        "# Databricks notebook source\n# Generated by make_chunk_seed.py from rag_app/docs (30 words, overlap 5); do not edit.\n"
        f"CHUNKS = {json.dumps(rows, indent=2)}\n",
        encoding="utf-8",
    )
    logger.info("main: wrote %d chunks to %s", len(rows), OUTPUT)


if __name__ == "__main__":
    main()
