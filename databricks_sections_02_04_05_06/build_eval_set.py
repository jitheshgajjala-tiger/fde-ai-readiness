"""Builds section_06_agent_eval/eval_set.jsonl from seed data so expected answers cannot drift from the tables."""

import json
import logging
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "notebooks"))

from seed_data import CUSTOMERS, ORDERS, PRODUCTS  # noqa: E402

logger = logging.getLogger(__name__)

OUTPUT = ROOT / "section_06_agent_eval" / "eval_set.jsonl"
NOTEBOOK_OUTPUT = ROOT / "notebooks" / "eval_data.py"
NOT_FOUND = ["not found", "no order", "does not exist", "doesn't exist", "could not find", "couldn't find", "unable to find"]


def _price(product_id: int) -> float:
    return next(p[3] for p in PRODUCTS if p[0] == product_id)


def _region(customer_id: int) -> str:
    return next(c[2] for c in CUSTOMERS if c[0] == customer_id)


def _late_days(order: tuple) -> int:
    return (date.fromisoformat(order[7]) - date.fromisoformat(order[5])).days


def build_eval_rows() -> list[dict]:
    """Return the evaluation questions with answers computed from ORDERS, CUSTOMERS and PRODUCTS."""
    delivered = [o for o in ORDERS if o[8] == "DELIVERED"]
    late = [o for o in delivered if _late_days(o) > 0]
    revenue = sum(o[3] * _price(o[2]) for o in ORDERS if o[8] != "CANCELLED")
    delivered_by_region: dict[str, int] = {}
    for order in delivered:
        region = _region(order[1])
        delivered_by_region[region] = delivered_by_region.get(region, 0) + 1
    top_region = max(delivered_by_region, key=delivered_by_region.get)
    on_time_rate = 100 * (len(delivered) - len(late)) / len(delivered)
    order_1011 = next(o for o in ORDERS if o[0] == 1011)
    cable_units = sum(o[3] for o in ORDERS if o[2] == 106)

    return [
        {"question": "How many orders are there in total?", "expected_any": [str(len(ORDERS))], "needs": "genie"},
        {"question": "How many orders were cancelled?", "expected_any": [str(sum(o[8] == "CANCELLED" for o in ORDERS))], "needs": "genie"},
        {"question": "What is the status of order 1007?", "expected_any": ["DELIVERED"], "needs": "uc_functions"},
        {"question": "How many days late was order 1011?", "expected_any": [str(_late_days(order_1011))], "needs": "uc_functions"},
        {"question": "Which orders were delivered after their promised date?", "expected_any": [str(o[0]) for o in late], "needs": "genie", "match": "all"},
        {"question": "What is the total revenue excluding cancelled orders?", "expected_any": [f"{revenue:.0f}"], "needs": "genie"},
        {"question": "How many units of Cable Pack were ordered in total?", "expected_any": [str(cable_units)], "needs": "genie"},
        {"question": "Which region has the most delivered orders?", "expected_any": [top_region], "needs": "genie"},
        {"question": "What share of delivered orders arrived on or before the promised date?", "expected_any": [f"{on_time_rate:.1f}", f"{on_time_rate:.2f}", str(int(on_time_rate * 10) / 10)], "needs": "genie"},
        {"question": "What is the status of order 9999?", "expected_any": NOT_FOUND, "needs": "uc_functions"},
        {"question": "What is 15% of 200?", "expected_any": ["30"], "needs": "none"},
        {"question": "How many days late was order 1008?", "expected_any": ["cancel", "not delivered", "no delivery"], "needs": "uc_functions"},
        {"question": "How many days do customers have to return unused products?", "expected_any": ["30"], "needs": "docs"},
        {"question": "Can digital products be returned?", "expected_any": ["cannot be returned", "can't be returned", "not be returned", "non-returnable"], "needs": "docs"},
    ]


def main() -> None:
    logging.basicConfig(level=logging.INFO)
    rows = build_eval_rows()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(json.dumps(row) for row in rows) + "\n", encoding="utf-8")
    NOTEBOOK_OUTPUT.write_text(
        "# Databricks notebook source\n# Generated by build_eval_set.py; do not edit.\n"
        f"EVAL_ROWS = {json.dumps(rows, indent=2)}\n",
        encoding="utf-8",
    )
    logger.info("main: wrote %d questions to %s and %s", len(rows), OUTPUT, NOTEBOOK_OUTPUT)


if __name__ == "__main__":
    main()
